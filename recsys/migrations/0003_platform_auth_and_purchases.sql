-- Additive migration 0003: local stand accounts, sessions, and isolated online profile purchases.
-- Safe on both clean synthetic PostgreSQL 17 databases and existing recommendations v4 dumps.

CREATE SEQUENCE IF NOT EXISTS recommendations.stand_client_excel_row_seq
    START WITH 1000000
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1;

CREATE TABLE IF NOT EXISTS recommendations.stand_accounts (
    account_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login text NOT NULL UNIQUE CHECK (login = lower(btrim(login)) AND login <> ''),
    password_hash text NOT NULL CHECK (btrim(password_hash) <> ''),
    profile_id text NOT NULL UNIQUE CHECK (btrim(profile_id) <> ''),
    client_id text NOT NULL UNIQUE REFERENCES recommendations.clients(client_id),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS recommendations.stand_sessions (
    token_hash bytea PRIMARY KEY CHECK (octet_length(token_hash) = 32),
    account_id bigint NOT NULL REFERENCES recommendations.stand_accounts(account_id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL CHECK (expires_at > created_at)
);

CREATE INDEX IF NOT EXISTS stand_sessions_account_id_idx
    ON recommendations.stand_sessions (account_id);

CREATE INDEX IF NOT EXISTS stand_sessions_expires_at_idx
    ON recommendations.stand_sessions (expires_at);

CREATE TABLE IF NOT EXISTS recommendations.online_purchases (
    purchase_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id text NOT NULL REFERENCES recommendations.orders(order_id),
    client_id text NOT NULL REFERENCES recommendations.clients(client_id),
    item_id text NOT NULL REFERENCES recommendations.historical_items(item_id),
    offer_id text REFERENCES recommendations.catalog_offers(offer_id),
    sku text,
    item_name text NOT NULL,
    purchased_week date NOT NULL,
    purchased_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS online_purchases_client_week_idx
    ON recommendations.online_purchases (client_id, purchased_week, purchase_id);

CREATE INDEX IF NOT EXISTS online_purchases_item_id_idx
    ON recommendations.online_purchases (item_id);
